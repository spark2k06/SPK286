"""Compile the sequential SPK286 microcode DSL (formats 1 through 5).

Source -> parsed IR -> symbols/validation -> expanded IR -> encoding -> output.
Only the Python standard library is required. Generated bytes have no timestamp
or host path. Labels name operations for debugging; executable branches are
deferred. Functional operation count is not historical 80286 timing.
"""

from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass, field
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import sys
from typing import Mapping

COMPILER_VERSION = "5.0"
FORMAT_VERSION = 5
MAX_ADDRESS_WIDTH = 12  # Current numeric CPU debug interface.
OPERATIONS = {"INVALID": 0, "FETCH_IMM16": 1, "MOVE": 2, "END": 3,
              "DECODE_MODRM": 4, "READ_REG16": 5, "READ_RM16": 6,
              "WRITE_REG16": 7, "WRITE_RM16": 8,
              "READ_REG16_TMP1": 9, "READ_RM16_TMP1": 10,
              "FETCH_IMM16_TMP1": 11, "FETCH_IMM8S_TMP1": 12,
              "READ_DST16": 13, "ALU": 14, "WRITE_RESULT_REG16": 15,
              "WRITE_RESULT_RM16": 16, "WRITE_RESULT_DST": 17, "COMMIT_FLAGS": 18, "CHECK_RM16": 19, "FETCH_IMM8S_TMP0": 20,
              "PUSH16": 21, "POP16": 22, "READ_IP16": 23, "TARGET_REL16": 24,
              "TARGET_ABS16": 25, "REDIRECT": 26, "ADJUST_SP16": 27, "COUNT": 28,
              "FETCH_IMM8": 29, "READ_FLAGS": 30, "RESTORE_FLAGS": 31,
              "SET_IF": 32, "HALT": 33, "REQUEST_EVENT": 34, "EVENT_ACK": 35,
              "EVENT_FLAGS": 36, "EVENT_CS": 37, "EVENT_IP": 38, "CLEAR_IF_TF": 39,
              "VECTOR_IP": 40, "VECTOR_CS": 41, "CONTEXT_COMMIT": 42,
              "POP16_TMP1": 43, "POP16_TMP2": 44, "IRET_COMMIT": 45}
ROOT = Path(__file__).resolve().parents[2]


@dataclass(frozen=True)
class Location:
    file: str
    line: int
    entry: str = ""


class CompileError(ValueError):
    def __init__(self, location: Location, message: str):
        context = f" instruction {location.entry}:" if location.entry else ""
        super().__init__(f"{location.file}:{location.line}:{context} error: {message}")


@dataclass(frozen=True)
class Statement:
    location: Location
    operation: str
    operands: tuple[str, ...]
    text: str


@dataclass(frozen=True)
class Label:
    location: Location
    name: str
    statement_index: int


@dataclass
class Block:
    location: Location
    format_version: int = 1
    statements: list[Statement] = field(default_factory=list)
    labels: list[Label] = field(default_factory=list)


@dataclass(frozen=True)
class MicroOp:
    location: Location
    operation: str
    operands: tuple[str, ...]
    statement: str
    address: int
    # Future timing metadata belongs in the IR/schema, not speculative ROM bits.


@dataclass(frozen=True)
class Program:
    operations: tuple[MicroOp, ...]
    entries: dict[str, int]
    labels: dict[str, int]
    source_hashes: dict[str, str]
    address_width: int
    depth: int
    format_version: int

    @property
    def word_width(self) -> int:
        return {1: 2, 2: 4, 3: 5, 4: 5, 5: 6}[self.format_version]


def parse_statement(text: str, location: Location, format_version: int = 1) -> Statement:
    extensions = {
        'CHECK_RM16': ('CHECK_RM16', ()),
        'FETCH_IMM8S -> TMP0': ('FETCH_IMM8S_TMP0', ('TMP0',)),
        'PUSH16 DECODED TMP0': ('PUSH16', ('DECODED', 'TMP0')),
        'POP16 -> TMP0': ('POP16', ('TMP0',)),
        'READ_IP16 -> TMP0': ('READ_IP16', ('TMP0',)),
        'TARGET_REL16 TMP1': ('TARGET_REL16', ('TMP1',)),
        'TARGET_ABS16 TMP0': ('TARGET_ABS16', ('TMP0',)),
        'REDIRECT DECODED': ('REDIRECT', ('DECODED',)),
        'ADJUST_SP16 TMP1': ('ADJUST_SP16', ('TMP1',)),
        'COUNT DECODED': ('COUNT', ('DECODED',)),
    }
    normalized = re.sub(r'\s*->\s*', ' -> ', ' '.join(text.split()))
    event_extensions = {
        'FETCH_IMM8 -> TMP0': 'FETCH_IMM8', 'READ_FLAGS -> TMP0': 'READ_FLAGS',
        'RESTORE_FLAGS TMP0': 'RESTORE_FLAGS', 'SET_IF DECODED': 'SET_IF',
        'HALT': 'HALT', 'REQUEST_EVENT DECODED': 'REQUEST_EVENT',
        'EVENT_ACK': 'EVENT_ACK', 'EVENT_FLAGS -> TMP0': 'EVENT_FLAGS',
        'EVENT_CS -> TMP0': 'EVENT_CS', 'EVENT_IP -> TMP0': 'EVENT_IP',
        'CLEAR_IF_TF': 'CLEAR_IF_TF', 'VECTOR_IP -> TMP0': 'VECTOR_IP',
        'VECTOR_CS -> TMP1': 'VECTOR_CS', 'CONTEXT_COMMIT TMP0 TMP1': 'CONTEXT_COMMIT',
        'POP16 -> TMP1': 'POP16_TMP1', 'POP16 -> TMP2': 'POP16_TMP2',
        'IRET_COMMIT TMP0 TMP1 TMP2': 'IRET_COMMIT',
    }
    if format_version >= 5 and normalized in event_extensions:
        return Statement(location, event_extensions[normalized], (), text)
    if format_version >= 4 and normalized in extensions:
        op, args = extensions[normalized]
        return Statement(location, op, args, text)
    if text in ("END", "DECODE_MODRM", "COMMIT_FLAGS"):
        return Statement(location, text, (), text)
    if re.match(r'ALU\b', text):
        if not re.fullmatch(r'ALU\s+DECODED\s+TMP0\s*,\s*TMP1\s*->\s*TMP2\s+FLAGS_DECODED', text):
            raise CompileError(location, 'invalid ALU operation, operands or FLAGS policy')
        return Statement(location, 'ALU', ('DECODED', 'TMP0', 'TMP1', 'TMP2', 'FLAGS_DECODED'), text)
    result = re.fullmatch(r'TMP2\s*->\s*(REG16|RM16|DST)\s+IF_WRITE', text)
    if result:
        return Statement(location, 'WRITE_RESULT_' + result[1], ('TMP2',), text)
    match = re.fullmatch(r"([A-Z][A-Z0-9_]*)\s*->\s*([A-Z][A-Z0-9_]*)", text)
    if match:
        source, destination = match.groups()
        if format_version >= 3 and source in ('FETCH_IMM16', 'READ_REG16', 'READ_RM16') and destination == 'TMP1':
            return Statement(location, source + '_TMP1', (destination,), text)
        if source == 'FETCH_IMM8S':
            return Statement(location, 'FETCH_IMM8S_TMP1', (destination,), text)
        if source == 'READ_DST16':
            return Statement(location, source, (destination,), text)
        if source in ("FETCH_IMM16", "READ_REG16", "READ_RM16"):
            return Statement(location, source, (destination,), text)
        if destination in ("REG16", "RM16"):
            return Statement(location, "WRITE_" + destination, (source,), text)
        return Statement(location, "MOVE", (source, destination), text)
    raise CompileError(location, f"unknown or malformed micro-operation: {text}")


def parse_source(name: str, source: str) -> list[Block]:
    blocks: list[Block] = []
    version_seen = 0
    current: Block | None = None
    for line, raw in enumerate(source.splitlines(), 1):
        text = raw.partition("#")[0].strip()
        if not text:
            continue
        location = Location(name, line, current.location.entry if current else "")
        if not version_seen:
            if text not in tuple(f'microcode_format {v}' for v in range(1, 6)):
                raise CompileError(location, "expected microcode_format 1, 2, 3, 4 or 5")
            version_seen = int(text[-1])
            continue
        if text.startswith("instruction"):
            match = re.fullmatch(r"instruction ([A-Z][A-Z0-9_]*):", text)
            if not match:
                raise CompileError(location, "malformed instruction declaration")
            current = Block(Location(name, line, match[1]), format_version=version_seen)
            blocks.append(current)
        elif current is None:
            raise CompileError(location, "statement outside an instruction")
        elif re.fullmatch(r"[a-z][a-z0-9_]*:", text):
            current.labels.append(Label(location, text[:-1], len(current.statements)))
        else:
            current.statements.append(parse_statement(text, location, version_seen))
    if not version_seen or not blocks:
        raise CompileError(Location(name, 1), "source requires format version and an instruction")
    return blocks


def validate_block(block: Block) -> None:
    if any(OPERATIONS.get(s.operation, 0) >= 29 for s in block.statements):
        validate_event_block(block)
        return
    if block.format_version >= 3:
        validate_datapath_block(block)
        return
    temporary_defined = False
    modrm_defined = False
    ended = False
    for statement in block.statements:
        loc = statement.location
        if ended:
            raise CompileError(loc, "unreachable statement after END")
        if block.format_version == 1 and statement.operation not in ("FETCH_IMM16", "MOVE", "END"):
            raise CompileError(loc, "operand operations require microcode_format 2")
        if statement.operation == "FETCH_IMM16":
            if statement.operands != ("TMP0",):
                raise CompileError(loc, f"invalid FETCH_IMM16 operand {statement.operands[0]}; expected TMP0")
            temporary_defined = True
        elif statement.operation == "MOVE":
            if statement.operands != ("TMP0", "DST"):
                raise CompileError(loc, f"invalid transfer operands {' -> '.join(statement.operands)}; expected TMP0 -> DST")
            if not temporary_defined:
                raise CompileError(loc, "TMP0 read before FETCH_IMM16 defines it")
        elif statement.operation == "END":
            ended = True
        elif statement.operation == "DECODE_MODRM":
            if modrm_defined:
                raise CompileError(loc, "ModR/M decoded more than once in an entry")
            modrm_defined = True
        elif statement.operation in ("READ_REG16", "READ_RM16", "WRITE_REG16", "WRITE_RM16"):
            if not modrm_defined:
                raise CompileError(loc, "operand used before DECODE_MODRM defines its context")
            if statement.operands != ("TMP0",):
                raise CompileError(loc, f"invalid {statement.operation} operand; expected TMP0")
            if statement.operation.startswith("READ_"):
                temporary_defined = True
            elif not temporary_defined:
                raise CompileError(loc, "TMP0 read before a fetch/operand read defines it")
        else:
            raise CompileError(loc, f"unknown micro-operation {statement.operation}")
    if not ended:
        raise CompileError(block.location, "missing END")


def validate_event_block(block: Block) -> None:
    """Bounded event grammar: each sequence has one explicit commit/terminal.

    These are functional service protocols, independent of instruction names or
    x86 encodings. Disallow incomplete frames, reordered pops and work after a
    context commit. REQUEST_EVENT transfers ownership without retiring when
    taken; END is its sole fall-through for an untaken conditional request.
    """
    if block.format_version < 5:
        raise CompileError(block.location, 'event operations require microcode_format 5')
    sequences = (
        ('READ_FLAGS', 'PUSH16', 'END'),
        ('POP16', 'RESTORE_FLAGS', 'END'),
        ('SET_IF', 'END'), ('HALT', 'END'), ('REQUEST_EVENT', 'END'),
        ('FETCH_IMM8', 'REQUEST_EVENT', 'END'),
        ('POP16', 'POP16_TMP1', 'POP16_TMP2', 'IRET_COMMIT', 'END'),
        ('EVENT_ACK', 'EVENT_FLAGS', 'PUSH16', 'EVENT_CS', 'PUSH16',
         'EVENT_IP', 'PUSH16', 'CLEAR_IF_TF', 'VECTOR_IP', 'VECTOR_CS', 'CONTEXT_COMMIT', 'END'),
    )
    ops = tuple(s.operation for s in block.statements)
    if ops not in sequences:
        raise CompileError(block.location, 'invalid event service ordering, temporary lifetime or completion')
    for s in block.statements:
        if s.operation == 'PUSH16' and s.operands != ('DECODED', 'TMP0'):
            raise CompileError(s.location, 'invalid frame push source')
        if s.operation == 'POP16' and s.operands != ('TMP0',):
            raise CompileError(s.location, 'invalid first pop destination')


def validate_datapath_block(block: Block) -> None:
    defined = set()
    context = ended = pending_flags = result_handled = committed = False
    targeted = redirected = counted = stacked = checked = popped = False
    for statement in block.statements:
        op, args, loc = statement.operation, statement.operands, statement.location
        if ended:
            raise CompileError(loc, 'unreachable statement after END')
        if redirected and op != 'END':
            raise CompileError(loc, 'work after REDIRECT')
        if OPERATIONS.get(op, 0) >= 19 and block.format_version < 4:
            raise CompileError(loc, 'stack/control operations require microcode_format 4')
        if committed and op != 'END':
            raise CompileError(loc, 'work after FLAGS commit')
        if op == 'END':
            if targeted and not redirected:
                raise CompileError(loc, 'missing REDIRECT for formed target')
            if pending_flags:
                raise CompileError(loc, 'missing COMMIT_FLAGS')
            ended = True
        elif op == 'DECODE_MODRM':
            if context:
                raise CompileError(loc, 'ModR/M decoded more than once in an entry')
            context = True
        elif op in ('TARGET_REL16', 'TARGET_ABS16'):
            if targeted or pending_flags:
                raise CompileError(loc, 'target overwritten or pending FLAGS')
            if args[0] not in defined:
                raise CompileError(loc, 'undefined target temporary')
            targeted = True
        elif op == 'REDIRECT':
            if not targeted or pending_flags:
                raise CompileError(loc, 'REDIRECT requires target and no pending FLAGS')
            redirected = True
        elif op == 'CHECK_RM16':
            if not context or stacked:
                raise CompileError(loc, 'CHECK_RM16 requires context before stack transfer')
            checked = True
        elif op == 'PUSH16':
            if 'TMP0' not in defined or stacked or pending_flags:
                raise CompileError(loc, 'PUSH16 requires defined source and unique stack transfer')
            stacked = True
        elif op == 'POP16':
            if stacked or pending_flags:
                raise CompileError(loc, 'POP16 requires unique stack transfer')
            stacked = True
            defined.add('TMP0')
            popped = True
        elif op == 'ADJUST_SP16':
            if 'TMP1' not in defined or not stacked:
                raise CompileError(loc, 'ADJUST_SP16 requires stack transfer and defined adjustment')
        elif op == 'COUNT':
            if counted:
                raise CompileError(loc, 'count updated more than once')
            counted = True
        elif op == 'ALU':
            if not {'TMP0', 'TMP1'} <= defined:
                raise CompileError(loc, 'undefined ALU temporary')
            if pending_flags:
                raise CompileError(loc, 'pending ALU result overwritten')
            defined.add('TMP2')
            pending_flags = True
            result_handled = False
        elif op == 'COMMIT_FLAGS':
            if not pending_flags or not result_handled:
                raise CompileError(loc, 'FLAGS commit requires ALU and completed result disposition')
            pending_flags = False
            committed = True
        elif op.startswith('WRITE_RESULT_'):
            if 'TMP2' not in defined or result_handled:
                raise CompileError(loc, 'undefined or already consumed ALU result')
            if op != 'WRITE_RESULT_DST' and not context:
                raise CompileError(loc, 'operand used before DECODE_MODRM defines its context')
            result_handled = True
        elif op in ('FETCH_IMM16', 'FETCH_IMM16_TMP1', 'FETCH_IMM8S_TMP1',
                    'READ_REG16', 'READ_RM16', 'READ_REG16_TMP1', 'READ_RM16_TMP1', 'READ_DST16',
                    'FETCH_IMM8S_TMP0', 'READ_IP16'):
            if pending_flags:
                raise CompileError(loc, 'operand acquisition after ALU')
            target = 'TMP1' if op.endswith('_TMP1') else 'TMP0'
            if args != (target,):
                raise CompileError(loc, f'invalid {op} operand; expected {target}')
            if op.startswith(('READ_REG16', 'READ_RM16')) and not context:
                raise CompileError(loc, 'operand used before DECODE_MODRM defines its context')
            defined.add(target)
        elif op in ('WRITE_REG16', 'WRITE_RM16', 'MOVE'):
            if op == 'WRITE_RM16' and popped and not checked and block.format_version < 5:
                raise CompileError(loc, 'POP memory destination requires precheck')
            if pending_flags:
                raise CompileError(loc, 'ALU result requires explicit IF_WRITE disposition')
            if args != (('TMP0', 'DST') if op == 'MOVE' else ('TMP0',)) or 'TMP0' not in defined:
                raise CompileError(loc, 'invalid or undefined transfer operand')
            if op != 'MOVE' and not context:
                raise CompileError(loc, 'operand used before DECODE_MODRM defines its context')
        else:
            raise CompileError(loc, f'unknown micro-operation {op}')
    if not ended:
        raise CompileError(block.location, 'missing END')


def compile_sources(sources: Mapping[str, str], *, address_width: int | None = None,
                    rom_depth: int | None = None) -> Program:
    if not sources:
        raise CompileError(Location("<sources>", 1), "no .mc sources")
    blocks: list[Block] = []
    hashes: dict[str, str] = {}
    # Source names are stable relative POSIX paths, independent of input order.
    for name, source in sorted(sources.items()):
        path = PurePosixPath(name)
        if path.is_absolute() or ".." in path.parts or "\\" in name or ":" in name:
            raise CompileError(Location(name, 1), "source name must be a relative POSIX path")
        hashes[name] = hashlib.sha256(source.encode("utf-8")).hexdigest()
        blocks.extend(parse_source(name, source))

    entries: dict[str, int] = {}
    labels: dict[str, int] = {}
    operations: list[MicroOp] = []
    for block in blocks:
        entry = block.location.entry
        if entry in entries:
            raise CompileError(block.location, f"duplicate instruction entry {entry}")
        validate_block(block)
        base = len(operations)
        entries[entry] = base
        for label in block.labels:
            symbol = f"{entry}.{label.name}"
            if symbol in labels:
                raise CompileError(label.location, f"duplicate label {label.name}")
            if label.statement_index >= len(block.statements):
                raise CompileError(label.location, f"label {label.name} has no operation")
            labels[symbol] = base + label.statement_index
        # Every supported statement expands to one functional operation. The
        # word-fetch executor owns its two byte handshakes, not the sequencer.
        for statement in block.statements:
            operations.append(MicroOp(statement.location, statement.operation,
                                      statement.operands, statement.text, len(operations)))

    depth = rom_depth if rom_depth is not None else len(operations)
    width = address_width if address_width is not None else max(1, (depth - 1).bit_length())
    loc = operations[-1].location
    if depth < 1:
        raise CompileError(loc, "ROM depth must be positive")
    if not 1 <= width <= MAX_ADDRESS_WIDTH:
        raise CompileError(loc, f"address width must be 1..{MAX_ADDRESS_WIDTH}")
    if len(operations) > depth:
        raise CompileError(operations[depth].location, f"ROM overflow: depth {depth}")
    if depth > 1 << width:
        raise CompileError(loc, f"address-width overflow: depth {depth} exceeds {width} bits")
    return Program(tuple(operations), entries, labels, hashes, width, depth,
                   max(block.format_version for block in blocks))


def encode(operation: MicroOp) -> int:
    return OPERATIONS[operation.operation]


def resolve_symbol(program: Program, symbol: str) -> int:
    if symbol in program.entries:
        return program.entries[symbol]
    if symbol in program.labels:
        return program.labels[symbol]
    raise CompileError(Location("<symbols>", 1), f"unresolved symbol {symbol}")


def describe_pc(program: Program, address: int) -> str:
    if not 0 <= address < len(program.operations):
        raise CompileError(Location("<micro_pc>", 1), f"unmapped micro-PC {address}")
    op = program.operations[address]
    return (f"micro_pc 0x{address:04X} -> {op.location.file}:{op.location.line}: "
            f"instruction {op.location.entry}: {op.statement}")


def generate(program: Program) -> dict[str, str]:
    banner = f"// Generated by SPK286 microcode compiler {COMPILER_VERSION}. Do not edit.\n"
    width = program.address_width
    word_width = program.word_width
    operations = {name: value for name, value in OPERATIONS.items()
                  if value < {1: 4, 2: 9, 3: 19, 4: 29, 5: 46}[program.format_version]}
    package = banner + ("`timescale 1ns/1ps\n"
                        "// Public constants: standalone consumers use only a subset.\n"
                        "/* verilator lint_off UNUSEDPARAM */\n"
                        "package spk286_microcode_pkg;\n")
    package += f"    localparam integer MC_FORMAT_VERSION = {program.format_version};\n"
    package += f"    localparam integer MC_ADDR_WIDTH = {width};\n"
    package += f"    localparam integer MC_WORD_WIDTH = {word_width};\n"
    package += f"    localparam integer MC_DEPTH = {program.depth};\n"
    for name, value in operations.items():
        package += f"    localparam logic [MC_WORD_WIDTH-1:0] MC_{name} = {word_width}'d{value};\n"
    for name, address in program.entries.items():
        package += f"    localparam logic [MC_ADDR_WIDTH-1:0] MC_ENTRY_{name} = {width}'d{address};\n"
    package += "endpackage\n/* verilator lint_on UNUSEDPARAM */\n"

    rom = banner + """`timescale 1ns/1ps
module spk286_microcode_rom (
    input  logic [spk286_microcode_pkg::MC_ADDR_WIDTH-1:0] address,
    output logic [spk286_microcode_pkg::MC_WORD_WIDTH-1:0] word,
    output logic valid
);
    always_comb begin
        word = spk286_microcode_pkg::MC_INVALID;
        valid = 1'b1;
        case (address)
"""
    listing = f"SPK286 microcode compiler {COMPILER_VERSION}; format {program.format_version}; encoding {program.format_version}\n"
    mapping = []
    for op in program.operations:
        rom += f"            {width}'d{op.address}: word = spk286_microcode_pkg::MC_{op.operation};\n"
        names = [name for name, address in {**program.entries, **program.labels}.items() if address == op.address]
        for name in names:
            listing += f"{op.address:04X}  {name}:\n"
        listing += (f"{op.address:04X}  {encode(op):X}  {op.statement}"
                    f"  # {op.location.file}:{op.location.line}\n")
        mapping.append({**asdict(op), "word": encode(op)})
    rom += """            default: valid = 1'b0;
        endcase
    end
endmodule
"""
    symbols = {"schema_version": 1, "entries": program.entries, "labels": program.labels,
               "operations": mapping}
    metadata = {"schema_version": 1, "compiler_version": COMPILER_VERSION,
                "format_version": program.format_version, "encoding_version": program.format_version,
                "source_sha256": program.source_hashes, "address_width": width,
                "word_width": word_width, "rom_depth": program.depth,
                "used_words": len(program.operations), "unused_words": program.depth - len(program.operations),
                "instruction_entries": len(program.entries), "timing_metadata": None,
                "warnings": [], "validation": "PASS"}
    def json_text(value: object) -> str:
        return json.dumps(value, sort_keys=True, indent=2) + "\n"
    return {"spk286_microcode_pkg.sv": package, "spk286_microcode_rom.sv": rom,
            "spk286_microcode.lst": listing, "spk286_microcode_symbols.json": json_text(symbols),
            "spk286_microcode_validation.json": json_text(metadata)}


def emit(artifacts: Mapping[str, str], directory: Path, *, check: bool) -> bool:
    stale = []
    for name, content in artifacts.items():
        target = directory / name
        expected = content.encode("utf-8")
        if target.is_file() and target.read_bytes() == expected:
            continue
        if check:
            stale.append(name)
        else:
            directory.mkdir(parents=True, exist_ok=True)
            target.write_bytes(expected)
    if stale:
        print(f"MICROCODE CHECK FAIL: stale/missing {', '.join(stale)}; run make microcode", file=sys.stderr)
        return False
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, default=ROOT / "microcode/source")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "microcode/generated")
    parser.add_argument("--address-width", type=int)
    parser.add_argument("--rom-depth", type=int)
    parser.add_argument("--check", action="store_true", help="compare all generated bytes without modifying files")
    query = parser.add_mutually_exclusive_group()
    query.add_argument("--lookup", help="resolve an instruction or ENTRY.label symbol")
    query.add_argument("--pc", type=lambda value: int(value, 0), help="map a numeric micro-PC to source")
    args = parser.parse_args()
    sources = {path.relative_to(args.source_dir).as_posix(): path.read_text(encoding="utf-8")
               for path in sorted(args.source_dir.rglob("*.mc"))}
    program = compile_sources(sources, address_width=args.address_width, rom_depth=args.rom_depth)
    if args.lookup:
        print(f"{args.lookup} = 0x{resolve_symbol(program, args.lookup):04X}")
        return 0
    if args.pc is not None:
        print(describe_pc(program, args.pc))
        return 0
    if not emit(generate(program), args.output_dir, check=args.check):
        return 1
    print(f"MICROCODE {'CHECK' if args.check else 'GENERATION'} PASS: "
          f"{len(program.entries)} entries, {len(program.operations)} words, "
          f"{program.address_width}-bit addresses, {program.word_width}-bit control")
    return 0


