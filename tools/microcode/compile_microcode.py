@dataclass(frozen=True)
class Location:
    file: str
    line: int
    entry: str = ""


class CompileError(ValueError):
    def __init__(self, location: Location, message: str):
        context = f" instruction {location.entry}:" if location.entry else ""
        super().__init__(f"{location.file}:{location.line}:{context} error: {message}")


@dataclass(frozen=True)
class Statement:
    location: Location
    operation: str
    operands: tuple[str, ...]
    text: str


@dataclass(frozen=True)
class Label:
    location: Location
    name: str
    statement_index: int


@dataclass
class Block:
    location: Location
    format_version: int = 1
    statements: list[Statement] = field(default_factory=list)
    labels: list[Label] = field(default_factory=list)


@dataclass(frozen=True)
class MicroOp:
    location: Location
    operation: str
    operands: tuple[str, ...]
    statement: str
    address: int
    # Future timing metadata belongs in the IR/schema, not speculative ROM bits.


@dataclass(frozen=True)
class Program:
    operations: tuple[MicroOp, ...]
    entries: dict[str, int]
    labels: dict[str, int]
    source_hashes: dict[str, str]
    address_width: int
    depth: int
    format_version: int
    branch_targets: dict[int, int] = field(default_factory=dict)

    @property
    def word_width(self) -> int:
        return {1: 2, 2: 4, 3: 5, 4: 5, 5: 6, 6: 6, 7: 6, 8: 6, 9: 7, 10: 7, 11: 7, 12: 7, 13: 7, 14: 7, 15: 7, 16: 8, 17: 8, 18: 8, 19: 8, 20: 8, 21: 8, 22: 8, 23: 8, 24: 8, 25: 8, 26: 8, 27: 8}[self.format_version]


