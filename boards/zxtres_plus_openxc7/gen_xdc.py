"""Write the nextpnr-xilinx constraints for the ZXTRES+ demo.

  gen_xdc.py VIVADO_XDC OUTPUT.xdc CPU_MHZ

The pins come from boards/zxtres_plus/zxtres_demo.xdc, so both flows use
the same ones. nextpnr-xilinx reads one property per set_property and
create_clock; the Vivado bitstream options, clock groups and false paths
have no counterpart there and are left out. The clocks are constrained on
the oscillator pin and on the two global clock nets of the top.
"""
from pathlib import Path
import re
import sys


def main(source, output, cpu_mhz):
    lines = [f'# Generated by gen_xdc.py from {Path(source).name} for a {cpu_mhz:g} MHz CPU clock']
    pins = 0
    for match in re.finditer(r'set_property -dict \{PACKAGE_PIN (\S+) IOSTANDARD (\S+)\} '
                             r'\[get_ports (\{[^}]*\}|[^\]\s]+)\]', Path(source).read_text()):
        ball, standard, port = match.groups()
        lines.append(f'set_property PACKAGE_PIN {ball} [get_ports {port}]')
        lines.append(f'set_property IOSTANDARD {standard} [get_ports {port}]')
        pins += 1
    if pins != 23:
        sys.exit(f'{source}: {pins} pins, expected 23')
    lines.append('create_clock -period 20.000 [get_ports clk50mhz]')
    lines.append(f'create_clock -period {1000.0 / cpu_mhz:.3f} [get_nets clk_cpu]')
    lines.append('create_clock -period 40.000 [get_nets clk_pix]')
    Path(output).write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{output}: {pins} pins, CPU clock {cpu_mhz:g} MHz')


if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2], float(sys.argv[3]))
