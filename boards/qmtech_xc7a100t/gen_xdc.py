"""Write the XDC pin and clock constraints for the QMTECH XC7A100T core board.

Header-to-ball maps are those of litex-boards
(litex_boards/platforms/qmtech_artix7_fgg676.py); banks and clock-capable
pins were checked against the prjxray package_pins.csv for xc7a100tfgg676.
J2 uses banks 13-15 and J3 banks 34-35, all 3.3 V. CLK sits on J2:22 (H21,
IO_L13P_T2_MRCC_15) so it reaches a global buffer over dedicated clock routing.

Usage: python3 gen_xdc.py OUTPUT.xdc [CLK_MHZ]   (default 32 MHz: a 16 MHz 80286)
"""
import sys
from pathlib import Path

J2 = {7: "D26", 8: "E26", 9: "D25", 10: "E25", 11: "G26", 12: "H26", 13: "E23", 14: "F23",
      15: "F22", 16: "G22", 17: "J26", 18: "J25", 19: "G21", 20: "G20", 21: "H22", 22: "H21",
      23: "J21", 24: "K21", 25: "K26", 26: "K25", 27: "K23", 28: "K22", 29: "M26", 30: "N26",
      31: "L23", 32: "L22", 33: "P26", 34: "R26", 35: "M25", 36: "M24", 37: "N22", 38: "N21",
      39: "P24", 40: "P23", 41: "P25", 42: "R25", 43: "T25", 44: "T24", 45: "V21", 46: "U21",
      47: "W23", 48: "V23", 49: "Y23", 50: "Y22", 51: "AA25", 52: "Y25", 53: "AC24", 54: "AB24",
      55: "Y21", 56: "W21", 57: "Y26", 58: "W25", 59: "AC26", 60: "AB26"}
J3 = {7: "B5", 8: "A5", 9: "B4", 10: "A4", 11: "A3", 12: "A2", 13: "D4", 14: "C4",
      15: "C2", 16: "B2", 17: "E5", 18: "D5", 19: "C1", 20: "B1", 21: "E1", 22: "D1",
      23: "F2", 24: "E2", 25: "G4", 26: "F4", 27: "G2", 28: "G1", 29: "J4", 30: "H4",
      31: "H2", 32: "H1", 33: "H9", 34: "G9", 35: "M2", 36: "L2", 37: "L5", 38: "K5",
      39: "M4", 40: "L4", 41: "N3", 42: "N2", 43: "M6", 44: "M5", 45: "K1", 46: "J1",
      47: "R3", 48: "P3", 49: "T4", 50: "T3", 51: "P6", 52: "P5", 53: "N1", 54: "M1",
      55: "R1", 56: "P1", 57: "T2", 58: "R2", 59: "U2", 60: "U1"}

# Fixed positions first: the UART where LiteX puts it, CLK on a clock pin.
FIXED_J2 = {"UART_TX": 7, "UART_RX": 8, "CLK": 22}
ORDER_J2 = ([f"D[{i}]" for i in range(16)] +
            ["RESET", "READY_N", "S0_N", "S1_N", "M_IO", "COD_INTA_N", "HOLD", "HLDA",
             "INTR", "NMI", "PEREQ", "BUSY_N", "ERROR_N", "PEACK_N", "HALTED", "SHUTDOWN"])
ORDER_J3 = [f"A[{i}]" for i in range(24)] + ["BHE_N", "LOCK_N"]
BOARD = {"CLK50": "U22", "LED[0]": "T23", "LED[1]": "R23"}   # core board oscillator and LEDs


def assign():
    free_j2 = [ball for pin, ball in sorted(J2.items()) if pin not in FIXED_J2.values()]
    assert len(ORDER_J2) <= len(free_j2) and len(ORDER_J3) <= len(J3)
    pins = {name: J2[pin] for name, pin in FIXED_J2.items()}
    pins.update(zip(ORDER_J2, free_j2))
    pins.update(zip(ORDER_J3, [ball for _, ball in sorted(J3.items())]))
    pins.update(BOARD)
    assert len(set(pins.values())) == len(pins), "ball used twice"
    return pins


def main(output, clk_mhz=32.0):
    pins = assign()
    lines = [f"# Generated by gen_xdc.py for a {clk_mhz:g} MHz CLK - do not edit by hand"]
    for name, ball in pins.items():
        port = "{" + name + "}" if "[" in name else name
        lines.append(f"set_property PACKAGE_PIN {ball} [get_ports {port}]")
        lines.append(f"set_property IOSTANDARD LVCMOS33 [get_ports {port}]")
    lines.append(f"create_clock -period {1000.0 / clk_mhz:.3f} [get_ports CLK]")
    lines.append("create_clock -period 20.000 [get_ports CLK50]")
    Path(output).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{output}: {len(pins)} pins, CLK {clk_mhz:g} MHz")


if __name__ == "__main__":
    if not 2 <= len(sys.argv) <= 3:
        sys.exit(__doc__.strip().splitlines()[-1])
    main(sys.argv[1], float(sys.argv[2]) if len(sys.argv) == 3 else 32.0)
